




// 展示
function altconShowUI() {
    let rebuildTimeline = document.getElementById("rebuildTimeline")
    let showtimedata = document.getElementById("showtimedata")
    rebuildTimeline.classList.remove("hide")
    showtimedata.classList.remove("hide")

}

// 隐藏
function altconHideUI() {
    let rebuildTimeline = document.getElementById("rebuildTimeline")
    let showtimedata = document.getElementById("showtimedata")
    rebuildTimeline.classList.add("hide")
    showtimedata.classList.add("hide")
}





