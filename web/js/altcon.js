// 展示
function altconShowUI() {
    let altcon = document.getElementById("altcon")
    altcon.classList.remove("hide")
    let sound = document.getElementById("sound")
    sound.classList.add("hide")

}

// 隐藏
function altconHideUI() {
    let altcon = document.getElementById("altcon")
    altcon.classList.add("hide")
    let sound = document.getElementById("sound")
    sound.classList.remove("hide")
}


